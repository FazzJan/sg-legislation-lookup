#!/usr/bin/env python3
"""Build js/osint-phone.js: offline phone-number data for the OSINT tab.

Uses Google's libphonenumber data (via the `phonenumbers` Python package):
calling codes for every country, number-type patterns for the countries most
seen in Singapore work, and the carrier each number block was first issued to.

    pip install phonenumbers && python3 scripts/build_osint_phone.py
"""
import json, pathlib
import phonenumbers
from phonenumbers import PhoneMetadata
from phonenumbers.carrierdata import CARRIER_DATA

DETAIL = ["SG", "MY", "ID", "TH", "PH", "VN", "MM", "KH", "LA", "BN", "CN", "HK", "MO", "TW",
          "IN", "BD", "PK", "LK", "NP", "JP", "KR", "AU", "NZ", "GB", "US", "CA", "AE", "SA", "NG"]
CARRIER_REGIONS = ["SG", "MY", "ID", "TH", "PH", "VN", "MM", "KH", "LA", "BN", "CN", "HK", "BD"]
TYPES = ["mobile", "fixed_line", "voip", "toll_free", "premium_rate", "shared_cost", "uan", "personal_number", "pager"]

cc = {}
for code, regions in phonenumbers.COUNTRY_CODE_TO_REGION_CODE.items():
    cc[str(code)] = [r for r in regions if r != "001"] or ["001"]

meta = {}
for r in DETAIL:
    m = PhoneMetadata.metadata_for_region(r)
    if not m:
        continue
    t = {}
    for name in TYPES:
        d = getattr(m, name, None)
        if d and d.national_number_pattern:
            t[name] = d.national_number_pattern
    meta[r] = {"cc": m.country_code, "np": m.national_prefix or "", "all": m.general_desc.national_number_pattern, "t": t}

carriers = {}
codes = {str(PhoneMetadata.metadata_for_region(r).country_code) for r in CARRIER_REGIONS}
for prefix, names in CARRIER_DATA.items():
    p = str(prefix)
    if any(p.startswith(c) for c in codes) and names.get("en"):
        carriers[p] = names["en"]

out = pathlib.Path(__file__).resolve().parent.parent / "js" / "osint-phone.js"
body = json.dumps({"version": phonenumbers.__version__, "cc": cc, "meta": meta, "carriers": carriers}, separators=(",", ":"))
out.write_text("// Generated by scripts/build_osint_phone.py from libphonenumber data. Do not edit by hand.\n"
               f"window.OSINT_PHONE = {body};\n", encoding="utf-8")
print(f"{out.name}: {len(cc)} calling codes, {len(meta)} detailed countries, {len(carriers)} carrier prefixes, {out.stat().st_size // 1024} KB")
